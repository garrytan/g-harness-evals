#!/usr/bin/env bun
// Builds docs/scoreboard.md and the README's ranking tables from docs/scoreboard/entries/*.json and the committed results
// files each entry points at, and docs/reports-index.md from docs/scoreboard/reports.json.
// Every number comes from a results file; nothing is typed. Each README ranking table sits between a
// <!-- ranking:<run id>:<model> ... --> marker and <!-- ranking:end -->, one per main entry and model.
// A harness's rank is 1 plus the number of same-model harnesses whose paired cost-per-solved-task ratio against it has a
// 95% range wholly below 1, computed here from the run's per-task cost table, docs/scoreboard/paired-cost/<run id>.json,
// which scripts/scoreboard/paired-cost.ts derives from the run's trial records.
// Usage: bun scripts/scoreboard/build.ts            (write)
//        bun scripts/scoreboard/build.ts --check    (exit 1 when a committed page or a README ranking table differs)
// --check skips the reports index's "Not yet indexed" list, so a new run folder with no row never fails it.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import type { TrialRecord } from '../../runner/contracts.ts';
import { pairedCostRatio } from '../../runner/stats/frontier.ts';
import { trialValue } from '../matrix-analysis.ts';
import { CELL_FIELDS, validateEntry, validateReports, type Entry, type ReportRow, type Source } from './schema.ts';

export const RANKING_END = '<!-- ranking:end -->';
export const rankingStart = (runId: string, model: string) => `<!-- ranking:${runId}:${model} (generated by scripts/scoreboard/build.ts from the run's paired cost ratios; do not edit by hand) -->`;
const RANKING_START = /<!-- ranking:([a-z0-9-]+):([^():]+?) \(generated by scripts\/scoreboard\/build\.ts from the run's paired cost ratios; do not edit by hand\) -->/;

const DISCLOSURE_SUBJECTS: [RegExp, string][] = [
  [/openclaw/i, 'OpenClaw'], [/hermes/i, 'Hermes'], [/\bqm\b/i, 'QM'], [/\bgpt|openai|codex/i, 'OpenAI'], [/particle/i, 'Particle'], [/gstack/i, 'gstack'], [/gbrain/i, 'gbrain'],
];

export interface Comparison { a: string; b: string; verdict?: string | null; tested?: boolean | null }

export interface Row {
  id: string; harness: string; version: string; model: string; caveats: string[];
  passes: number; scored: number; pass_rate: number; pass_ci95: [number, number];
  usd_per_solved: number | null; usd_per_solved_ci95: [number, number] | null; usd_per_solved_interval_basis?: number;
  usd_per_trial: number; wall_median_s: number; call: string;
}

/** b's cost per solved task over a's, on the tasks both cells scored, with its paired task bootstrap 95% range. */
export interface PairRatio { a: string; b: string; tasks: number; ratio: number | null; ci95: [number, number] | null; note: string | null }

export interface Table {
  entry: Entry; rows: Row[]; pairs: PairRatio[]; basis: Record<string, number | null>; n_tasks: number | null; same_everywhere: number | null; mdd: [number, number] | null; mdd_holm: [number, number] | null;
  model_lines: string[]; lead: string; saturated: boolean;
}

export function getPath(obj: unknown, path: string): unknown {
  let cur: unknown[] = [obj];
  let spread = false;
  for (const tok of path.match(/[^.[\]]+|\[[^\]]*\]/g) ?? []) {
    const next: unknown[] = [];
    for (const v of cur) {
      if (tok.startsWith('[')) {
        const inner = tok.slice(1, -1);
        if (!Array.isArray(v)) throw new Error(`${path}: ${tok} applied to a non-list`);
        if (inner === '*') { next.push(...v); spread = true; }
        else if (/^\d+$/.test(inner)) next.push(v[Number(inner)]);
        else {
          const [k, want] = inner.split('=');
          const hits = v.filter((el) => el && typeof el === 'object' && String((el as Record<string, unknown>)[k!]) === want);
          if (hits.length !== 1) throw new Error(`${path}: ${tok} matched ${hits.length} items`);
          next.push(hits[0]);
        }
      } else {
        if (!v || typeof v !== 'object' || !(tok in v)) throw new Error(`${path}: no key ${tok}`);
        next.push((v as Record<string, unknown>)[tok]);
      }
    }
    cur = next;
  }
  return spread ? cur : cur[0];
}

export const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
export const usd = (x: number, d = 2) => `$${x.toFixed(d)}`;
const pts = (x: number) => (x * 100).toFixed(1);
const range = (r: [number, number], f: (x: number) => string) => `[${f(r[0])}, ${f(r[1])}]`;

const verdictOf = (c: Comparison) => (c.tested === false ? 'not tested' : c.verdict ?? 'no verdict recorded');

export function callPhrase(verdict: string, side: 'a' | 'b'): string {
  if (verdict === "can't tell apart") return "can't tell apart from";
  if (verdict === "can't tell: no room to improve") return "can't tell (no room to improve) against";
  if (verdict === 'behind') return side === 'a' ? 'behind' : 'ahead of';
  if (verdict === 'ahead') return side === 'a' ? 'ahead of' : 'behind';
  const within = /^within (\d+) points$/.exec(verdict);
  if (within) return side === 'a' ? `${verdict} of` : `at most ${within[1]} points ahead of`;
  return `${verdict}:`;
}

export function callFor(cell: string, modelOf: Map<string, string>, harnessOf: Map<string, string>, primary: Comparison[], secondary: Comparison[]): string {
  const sameModel = (c: Comparison) => (c.a === cell || c.b === cell) && modelOf.get(c.a) === modelOf.get(c.b);
  const other = (c: Comparison) => harnessOf.get(c.a === cell ? c.b : c.a) ?? (c.a === cell ? c.b : c.a);
  const mine = primary.filter(sameModel);
  if (mine.length) {
    const byPhrase = new Map<string, string[]>();
    for (const c of mine) {
      const phrase = callPhrase(verdictOf(c), c.a === cell ? 'a' : 'b');
      byPhrase.set(phrase, [...(byPhrase.get(phrase) ?? []), other(c)]);
    }
    return [...byPhrase].map(([phrase, names]) => `${phrase} ${names.join(', ')}`).join('; ');
  }
  const untested = secondary.filter((c) => sameModel(c) && !c.tested);
  if (untested.length) return `interval only, not tested (vs ${untested.map(other).join(', ')})`;
  return 'not compared';
}

export function costCallFor(cell: string, harnessOf: Map<string, string>, contrasts: Record<string, unknown>[], interval: string): string {
  const byPhrase = new Map<string, string[]>();
  for (const c of contrasts) {
    if (c.a !== cell && c.b !== cell) continue;
    const [lo, hi] = getPath(c, interval) as [number, number];
    if (typeof lo !== 'number' || typeof hi !== 'number') throw new Error(`${String(c.a)} vs ${String(c.b)}: ${interval} is not a [lo, hi] pair`);
    const bMinusA = hi < 0 ? -1 : lo > 0 ? 1 : 0;
    const mine = c.b === cell ? bMinusA : -bMinusA;
    const phrase = mine < 0 ? 'cheaper per trial than' : mine > 0 ? 'costs more per trial than' : "cost per trial: can't tell apart from";
    const other = String(c.a === cell ? c.b : c.a);
    byPhrase.set(phrase, [...(byPhrase.get(phrase) ?? []), harnessOf.get(other) ?? other]);
  }
  if (!byPhrase.size) return 'not compared';
  return [...byPhrase].map(([phrase, names]) => `${phrase} ${names.join(', ')}`).join('; ');
}

export function modelLines(cells: { id: string; model: string }[], primary: Comparison[]): string[] {
  const modelOf = new Map(cells.map((c) => [c.id, c.model]));
  const models = [...new Set(cells.map((c) => c.model))];
  return models.map((m) => {
    const pairs = primary.filter((c) => modelOf.get(c.a) === m && modelOf.get(c.b) === m);
    if (!pairs.length) return `**${m}:** no preregistered pairs.`;
    const counts = new Map<string, number>();
    for (const c of pairs) counts.set(verdictOf(c), (counts.get(verdictOf(c)) ?? 0) + 1);
    return `**${m}:** ${pairs.length} preregistered pairs: ${[...counts].map(([v, n]) => `${n} ${v}`).join(', ')}.`;
  });
}

export function buildTable(entry: Entry, readJson: (path: string) => unknown): Table {
  const base = dirname(entry.report);
  const read = (s: Source, cell?: string): unknown => {
    const v = getPath(readJson(join(base, s.file)), cell ? s.path.replaceAll('{cell}', cell) : s.path);
    if (s.scale === undefined && !s.per) return v;
    if (typeof v !== 'number') throw new Error(`${entry.run_id}: ${s.path} is not a number`);
    const per = s.per ? read(s.per, cell) : 1;
    if (typeof per !== 'number' || !(per > 0)) throw new Error(`${entry.run_id}: ${s.per!.path} is not a positive number`);
    return (v * (s.scale ?? 1)) / per;
  };
  const num = (v: unknown, what: string) => { if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`${entry.run_id}: ${what} is not a number`); return v; };
  const pair = (v: unknown, what: string): [number, number] => { if (!Array.isArray(v) || v.length !== 2) throw new Error(`${entry.run_id}: ${what} is not a [lo, hi] pair`); return [num(v[0], what), num(v[1], what)]; };
  const list = (v: unknown, what: string, nonEmpty = false): unknown[] => { if (!Array.isArray(v) || (nonEmpty && !v.length)) throw new Error(`${entry.run_id}: ${what} is not a${nonEmpty ? ' non-empty' : ''} list`); return v; };
  const missing = DISCLOSURE_SUBJECTS.filter(([re, s]) => entry.cells.some((c) => re.test(`${c.harness} ${c.model}`)) && !entry.disclosures.includes(s)).map(([, s]) => s);
  if (missing.length) throw new Error(`${entry.run_id}: disclosures must list ${missing.join(', ')}`);
  const family = list(read(entry.family), entry.family.path) as Record<string, unknown>[];
  const costFamily = entry.family.kind === 'cost_per_trial';
  const { a: aKey = 'a', b: bKey = 'b', verdict: verdictSrc, words } = entry.family;
  const primary: Comparison[] = costFamily ? [] : family.map((c) => {
    const [a, b] = [c[aKey], c[bKey]];
    if (typeof a !== 'string' || typeof b !== 'string') throw new Error(`${entry.run_id}: a comparison in ${entry.family.path} has no string ${aKey} and ${bKey}`);
    const raw = verdictSrc ? read(verdictSrc, a) : c.verdict;
    const verdict = words && typeof raw === 'string' ? words[raw] : raw;
    if (words && verdict === undefined && c.tested !== false) throw new Error(`${entry.run_id}: ${a} vs ${b}: verdict ${JSON.stringify(raw)} has no call word in family.words`);
    return { a, b, verdict: verdict as string | null | undefined, tested: c.tested as boolean | null | undefined };
  });
  const secondary = entry.secondary ? (read(entry.secondary) as Comparison[]) : [];
  const modelOf = new Map(entry.cells.map((c) => [c.id, c.model]));
  const harnessOf = new Map(entry.cells.map((c) => [c.id, c.harness]));
  const rows: Row[] = entry.cells.map((c) => {
    const src = (f: string) => (c.overrides as Record<string, Source> | undefined)?.[f] ?? (entry.fields as Record<string, Source>)[f];
    const v = Object.fromEntries(CELL_FIELDS.map((f) => [f, read(src(f)!, c.id)]));
    const basis = c.overrides?.usd_per_solved_interval_basis;
    const passes = num(v.passes, 'passes');
    if ((v.usd_per_solved === null) !== (v.usd_per_solved_ci95 === null)) throw new Error(`${entry.run_id}: ${c.id} has a cost per solved task without its 95% range, or the reverse`);
    if ((v.usd_per_solved === null) !== (passes === 0)) throw new Error(`${entry.run_id}: ${c.id} has ${passes} passes, so its cost per solved task must be ${passes === 0 ? 'null' : 'a number'}`);
    return {
      id: c.id, harness: c.harness, version: c.version, model: c.model, caveats: c.caveats ?? [],
      passes, scored: num(v.scored, 'scored'), pass_rate: num(v.pass_rate, 'pass_rate'), pass_ci95: pair(v.pass_ci95, 'pass_ci95'),
      usd_per_solved: v.usd_per_solved === null ? null : num(v.usd_per_solved, 'usd_per_solved'),
      usd_per_solved_ci95: v.usd_per_solved_ci95 === null ? null : pair(v.usd_per_solved_ci95, 'usd_per_solved_ci95'),
      ...(basis ? { usd_per_solved_interval_basis: num(read(basis, c.id), 'usd_per_solved_interval_basis') } : {}),
      usd_per_trial: num(v.usd_per_trial, 'usd_per_trial'), wall_median_s: num(v.wall_median_s, 'wall_median_s'),
      call: costFamily ? costCallFor(c.id, harnessOf, family, entry.family.interval!) : callFor(c.id, modelOf, harnessOf, primary, secondary),
    };
  });
  if (entry.role === 'other') return { entry, rows, pairs: [], basis: {}, n_tasks: null, same_everywhere: null, mdd: null, mdd_holm: null, model_lines: [], lead: entry.lead_note, saturated: false };
  const n_tasks = num(read(entry.tasks!), 'tasks');
  const same_everywhere = entry.same_everywhere!.reduce((n, s) => n + list(read(s), s.path).length, 0);
  const spread = (s: Source): [number, number] => { const xs = list(read(s), s.path, true).map((x) => num(x, s.path)); return [Math.min(...xs), Math.max(...xs)]; };
  const mdd = spread(entry.mdd!);
  const mdd_holm = entry.mdd_holm ? spread(entry.mdd_holm) : null;
  const power = `this run had less than an 80% chance to detect a gap smaller than ${pts(mdd[0])} to ${pts(mdd[1])} points${mdd_holm ? ` (${pts(mdd_holm[0])} to ${pts(mdd_holm[1])} at the first Holm step)` : ''}`;
  const saturated = same_everywhere * 2 >= n_tasks;
  const allNull = primary.length > 0 && primary.every((c) => verdictOf(c) === "can't tell apart");
  const lead = [
    saturated ? '**Saturated task set.**' : '',
    allNull ? `On these tasks pass rate can't separate the harnesses: ${same_everywhere} of ${n_tasks} tasks scored the same in every cell, and ${power}.` : `${same_everywhere} of ${n_tasks} tasks scored the same in every cell; ${power}.`,
    entry.lead_note,
  ].filter(Boolean).join(' ');
  const pc = entry.paired_cost!;
  const costs = readJson(pairedCostPath(entry.run_id)) as { schema?: string; run_id?: string; cells?: TaskCosts };
  if (costs.schema !== PAIRED_COST_SCHEMA || costs.run_id !== entry.run_id || !costs.cells) throw new Error(`${entry.run_id}: ${pairedCostPath(entry.run_id)} is not this run's per-task cost table (run bun scripts/scoreboard/paired-cost.ts)`);
  const pairs = pairedCostRatios(entry.cells, costs.cells, { seed: num(read(pc.seed), 'paired_cost.seed'), draws: num(read(pc.draws), 'paired_cost.draws') });
  const basis = Object.fromEntries(entry.cells.map((c) => {
    const tasks = Object.values(costs.cells![c.id] ?? {});
    const solves = tasks.reduce((n, s) => n + s.solves, 0);
    return [c.id, solves === 0 ? null : tasks.reduce((n, s) => n + s.usd, 0) / solves];
  }));
  return { entry, rows, pairs, basis, n_tasks, same_everywhere, mdd, mdd_holm, model_lines: modelLines(entry.cells, primary), lead, saturated };
}

export const PAIRED_COST_SCHEMA = 'harness-evals/paired-cost@1';
export const pairedCostPath = (runId: string) => `docs/scoreboard/paired-cost/${runId}.json`;

/** Per cell, then per task: recorded spend, scored passes and scored trials. */
export type TaskCosts = Record<string, Record<string, { usd: number; solves: number; scored: number }>>;

/** Each task's recorded spend (usage.usd less usage.usd_reserved, plus the extra fields) and scored passes per cell, from the trial records. A
 *  trial in lookups is a fail whatever its grade, as in the run's analysis, and a lookup id with no trial record is
 *  refused, as there. */
export function perTaskCosts(cells: { id: string }[], records: TrialRecord[], lookups: Set<string>, extraUsd: string[]): TaskCosts {
  const recordIds = new Set(records.map((t) => t.trial_id));
  const unknownLookups = [...lookups].filter((id) => !recordIds.has(id));
  if (unknownLookups.length) throw new Error(`paired_cost.lookup_fails names ${unknownLookups.length} trial(s) with no record: ${unknownLookups.slice(0, 5).join(', ')}`);
  const per: TaskCosts = Object.fromEntries(cells.map((c) => [c.id, {}]));
  for (const t of records) {
    const tasks = per[t.cell];
    if (!tasks) continue;
    const s = tasks[t.task] ?? { usd: 0, solves: 0, scored: 0 };
    s.usd += (t.usage?.usd ?? 0) - (t.usage?.usd_reserved ?? 0) + extraUsd.reduce((sum, f) => { const v = f.split('.').reduce<unknown>((o, k) => (o && typeof o === 'object' ? (o as Record<string, unknown>)[k] : undefined), t); return sum + (typeof v === 'number' ? v : 0); }, 0);
    const v = trialValue(t);
    if (v !== null) { s.scored += 1; s.solves += v === 1 && lookups.has(t.trial_id) ? 0 : v; }
    tasks[t.task] = s;
  }
  const empty = cells.filter((c) => Object.keys(per[c.id]!).length === 0).map((c) => c.id);
  if (empty.length) throw new Error(`paired_cost.trials holds no trial record for ${empty.join(', ')}`);
  return per;
}

/** Every same-model pair of cells, once, in entry order, on the tasks both cells scored, through
 *  runner/stats/frontier.ts pairedCostRatio. */
export function pairedCostRatios(cells: { id: string; model: string }[], costs: TaskCosts, opts: { seed: number; draws: number }): PairRatio[] {
  const out: PairRatio[] = [];
  cells.forEach((ca, i) => cells.slice(i + 1).filter((cb) => cb.model === ca.model).forEach((cb) => {
    const A = costs[ca.id] ?? {}, B = costs[cb.id] ?? {};
    const tasks = Object.keys(A).filter((k) => A[k]!.scored > 0 && (B[k]?.scored ?? 0) > 0).sort();
    const r = pairedCostRatio(tasks.map((task) => ({ task, usd_a: A[task]!.usd, solves_a: A[task]!.solves, usd_b: B[task]!.usd, solves_b: B[task]!.solves })), opts);
    out.push({ a: ca.id, b: cb.id, tasks: r.tasks, ratio: r.ratio, ci95: r.ci95, note: r.note });
  }));
  return out;
}

/** x's cost per solved task over y's, read from the pair in either direction (the reverse is the exact reciprocal). */
export function ratioOf(pairs: PairRatio[], x: string, y: string): PairRatio | null {
  const p = pairs.find((q) => (q.a === y && q.b === x) || (q.a === x && q.b === y));
  if (!p || p.a === y) return p ?? null;
  if (p.ratio === 0 || (p.ci95 !== null && p.ci95[0] <= 0)) return { a: y, b: x, tasks: p.tasks, ratio: null, ci95: null, note: 'one side spent nothing on some paired tasks, so the reversed ratio is undefined' };
  return { a: y, b: x, tasks: p.tasks, ratio: p.ratio === null ? null : 1 / p.ratio, ci95: p.ci95 ? [1 / p.ci95[1], 1 / p.ci95[0]] : null, note: p.note };
}

export interface RankedRow { row: Row; cost: number | null; rank: number | null; cheapest: boolean; vs_cheapest: PairRatio | null }

/** One model's rows: rank is 1 plus the number of other rows whose ratio over this row has a 95% range wholly below 1.
 *  costOf is each row's cost per solved task on the ratios' basis (default: its headline); a row with none is unranked.
 *  The cheapest row is the priced row no other row undercuts on its paired ratio, else the lowest costOf; every other
 *  row carries its ratio over that row. Sorted by rank, then costOf. */
export function rankRows(rows: Row[], pairs: PairRatio[], costOf: (r: Row) => number | null = (r) => r.usd_per_solved): RankedRow[] {
  const priced = rows.filter((r) => costOf(r) !== null);
  const cheapest = priced.find((r) => priced.every((o) => o === r || (ratioOf(pairs, o.id, r.id)?.ratio ?? 1) >= 1))
    ?? priced.reduce<Row | null>((best, r) => (best === null || costOf(r)! < costOf(best)! ? r : best), null);
  const clearlyBelow = (p: PairRatio | null) => p?.ci95 != null && p.ci95[1] < 1;
  return rows
    .map((r) => ({
      row: r,
      cost: costOf(r),
      rank: costOf(r) === null ? null : 1 + rows.filter((o) => o !== r && clearlyBelow(ratioOf(pairs, o.id, r.id))).length,
      cheapest: r === cheapest,
      vs_cheapest: cheapest && r !== cheapest ? ratioOf(pairs, r.id, cheapest.id) : null,
    }))
    .sort((x, y) => (x.rank ?? Infinity) - (y.rank ?? Infinity) || (x.cost ?? Infinity) - (y.cost ?? Infinity));
}

const costCell = (r: Row) => r.usd_per_solved === null || r.usd_per_solved_ci95 === null
  ? 'no solved tasks'
  : r.usd_per_solved_interval_basis === undefined
  ? `${usd(r.usd_per_solved)} ${range(r.usd_per_solved_ci95, (x) => usd(x))}`
  : `${usd(r.usd_per_solved)} (range from trial records: ${usd(r.usd_per_solved_interval_basis)} ${range(r.usd_per_solved_ci95, (x) => usd(x))})`;

function receipts(t: Table, from: string): string {
  const e = t.entry;
  const rel = (p: string) => relative(from, p);
  const files = [...new Set([e.family.file, ...Object.values(e.fields).map((s) => s.file)])];
  return [
    `[report](${rel(e.report)})`,
    ...files.map((f) => `[${f.split('/').pop()}](${rel(join(dirname(e.report), f))})`),
    `results PR ${e.results_pr}`,
    e.claim_check ? `claim check: ${e.claim_check.reader} on ${e.claim_check.pr}` : 'no claim check on record',
  ].join(' · ');
}

const caveatLines = (t: Table, prefix: string): string[] => [
  ...t.entry.caveats.map((c) => `- ${prefix ? `${prefix}: ` : ''}${c}`),
  ...t.rows.flatMap((r) => r.caveats.map((c) => `- ${prefix ? `${prefix}, ` : ''}${r.harness}, ${r.model}: ${c}`)),
];

export function renderPage(tables: Table[], disclosures: Record<string, string>): string {
  const mains = tables.filter((t) => t.entry.role === 'main');
  const others = tables.filter((t) => t.entry.role === 'other');
  for (const o of others) if (!mains.some((m) => m.entry.task_set.id === o.entry.task_set.id)) throw new Error(`${o.entry.run_id}: no main entry has task set ${o.entry.task_set.id}`);
  const out: string[] = [
    '# Which harness should I use?',
    '',
    '<!-- Generated by scripts/scoreboard/build.ts from docs/scoreboard/entries/*.json and the results files they name. Do not edit by hand. -->',
    '',
    'One section per task set. **Never compare numbers across task sets:** different tasks give different pass rates. Every number below is read from a committed results file; the receipts line under each table names the files.',
    '',
  ];
  for (const t of mains) {
    const e = t.entry;
    out.push(`## ${e.task_set.label} (${e.run_id}, ${e.task_set.split}, ${e.task_set.public ? 'public' : 'sealed'})`, '', t.lead, '');
    for (const l of t.model_lines) out.push(`- ${l}`);
    out.push('', '| Harness | Version | Model | Pass rate [95% range] | Passes / scored | Cost per solved task [95% range] | Cost per trial | Median time per trial | Preregistered call |', '|---|---|---|---|---|---|---|---|---|');
    for (const r of t.rows) out.push(`| ${r.harness} | ${r.version} | ${r.model} | ${pct(r.pass_rate)} ${range(r.pass_ci95, pct)} | ${r.passes} / ${r.scored} | ${costCell(r)} | ${usd(r.usd_per_trial, 3)} | ${r.wall_median_s.toFixed(1)} s | ${r.call} |`);
    out.push('', '**Caveats:**', '', ...caveatLines(t, ''));
    if (e.verdict) out.push(`- Why null? verdict: **${e.verdict.word}**. See [the glossary below](#how-to-read-this) and the report.`);
    out.push('', `**Receipts:** ${receipts(t, 'docs')}`, '');
    const same = others.filter((o) => o.entry.task_set.id === e.task_set.id);
    if (!same.length) continue;
    out.push(
      '### Same tasks, other runs',
      '',
      'Each of these runs used the same task set on its own dates, repetitions and machines. Compare rows within one run; each call comes from that run\'s own preregistered comparisons.',
      '',
    );
    for (const o of same) out.push(`- **${o.entry.run_id}:** ${o.lead}`);
    out.push('', '| Harness | Version | Model | Run | Pass rate [95% range] | Passes / scored | Cost per solved task [95% range] | Cost per trial | Median time per trial | Run\'s preregistered call |', '|---|---|---|---|---|---|---|---|---|---|');
    for (const o of same) for (const r of o.rows) out.push(`| ${r.harness} | ${r.version} | ${r.model} | [${o.entry.run_id}](${relative('docs', o.entry.report)}) | ${pct(r.pass_rate)} ${range(r.pass_ci95, pct)} | ${r.passes} / ${r.scored} | ${costCell(r)} | ${usd(r.usd_per_trial, 3)} | ${r.wall_median_s.toFixed(1)} s | ${r.call} |`);
    out.push('', '**Caveats:**', '', ...same.flatMap((o) => caveatLines(o, o.entry.run_id)), '');
    for (const o of same) out.push(`**Receipts, ${o.entry.run_id}:** ${receipts(o, 'docs')}`, '');
  }
  out.push(
    '## How to read this',
    '',
    '- **Words:** every term is defined in the [glossary](glossary.md). Every report, with its grade, status and verdict, is in the [reports index](reports-index.md).',
    '- **Pass rate:** each task\'s share of passing scored tries, averaged over the tasks.',
    '- **95% range:** the task-clustered bootstrap interval: tasks are resampled with replacement, so a few lucky tasks can\'t narrow it.',
    '- **Can\'t tell apart:** the run\'s preregistered test, adjusted for the number of comparisons (Holm), found no difference. It does not mean equal: the run had less than an 80% chance to detect a gap smaller than its minimum detectable difference.',
    '- **Behind / ahead of:** the run\'s preregistered test, adjusted for the number of comparisons (Holm), found a gap in that direction.',
    '- **Within N points of:** the run\'s preregistered non-inferiority test, adjusted (Holm), showed the harness is no more than N points below the one it is compared with, N being the margin the preregistration set. Read from the other row it says **at most N points ahead of**. It does not mean equal.',
    '- **Interval only, not tested:** the run reports a range for this pair but its preregistration made no test of it.',
    '- **Cheaper per trial / costs more per trial:** the run\'s preregistered cost contrast has a 95% range wholly below or wholly above zero. **Cost per trial: can\'t tell apart:** that range includes zero.',
    '- **Cost per solved task:** what the cell spent at list price, metered by our proxy, divided by its passes. **Cost per trial** is the same spend divided by the trials recorded.',
    '- **Rank (README only):** a harness\'s rank is 1 plus the number of harnesses on the same model and task set that cost clearly less per solved task: on the tasks both scored, the 95% range of their paired cost ratio (tasks resampled with replacement) sits wholly below 1. Harnesses can share a rank, and ranks can skip (1, 1, 3). The costs are each trial record\'s own, after any correction the run has had (the 2026-11-09 correction today, and for frontier-harness-2026-11 also the 2026-11-10 correction), so a ‡ marks a row where that differs from the cost per solved task shown. These ranges are descriptive, not a preregistered test.',
    '- **Cost vs the cheapest (README only):** a harness\'s cost per solved task divided by that of the cheapest harness on the same model, over the tasks both scored, with the same paired 95% range. The cheapest is the harness no other undercuts on the tasks both scored.',
    '- **Median time per trial:** wall-clock time from start to finish of one trial.',
    '- **Saturated task set:** half or more of the tasks scored the same in every cell, so the tasks, not the harness, decide most of the score.',
    '- **KEEP:** tested on frontier models and it helps, or it is needed; keep it on. **FIX-METHOD:** the test could not tell, for a named reason; fix the test before deciding. **CUT-CANDIDATE:** tested fairly and it did not help; a candidate to switch off.',
    '',
    '## Disclosures',
    '',
  );
  const subjects = [...new Set(tables.flatMap((t) => t.entry.disclosures))];
  for (const s of subjects) {
    const line = disclosures[s];
    if (!line) throw new Error(`no disclosure line for ${s} in docs/scoreboard/disclosures.json`);
    out.push(line, '');
  }
  return out.join('\n').trimEnd() + '\n';
}

const times = (x: number) => `${x.toFixed(2)}x`;
const vsCheapestCell = (r: RankedRow) => r.cheapest ? 'cheapest'
  : r.vs_cheapest?.ratio == null ? 'no paired ratio'
  : `${times(r.vs_cheapest.ratio)} ${r.vs_cheapest.ci95 === null ? `(no range: ${r.vs_cheapest.note})` : range(r.vs_cheapest.ci95, times)}`;
const otherBasis = (r: RankedRow) => r.cost !== null && r.row.usd_per_solved !== null && usd(r.cost) !== usd(r.row.usd_per_solved);
const behindOf = (r: Row) => r.call.split('; ').filter((s) => s.startsWith('behind ')).map((s) => s.slice('behind '.length));

/** One README ranking table: the model line, the table, a † line for each row its run's preregistered test found behind,
 *  and a ‡ line naming the rows whose cost on the ratios' basis (the per-task table, after any correction the entry
 *  names) differs from the cost shown. */
export function renderRankingBlock(t: Table, model: string): string {
  const rows = t.rows.filter((r) => r.model === model);
  if (!rows.length) throw new Error(`${t.entry.run_id} has no cells on ${model}`);
  const ranked = rankRows(rows, t.pairs, (r) => t.basis[r.id] ?? null);
  const out = [rankingStart(t.entry.run_id, model), `**${model}**`, '', '| Rank | Harness | Cost vs the cheapest (95% range) | Cost per solved task (95% range) | Pass rate (95% range) | Median time per try |', '|---|---|---|---|---|---|'];
  for (const r of ranked) out.push(`| ${r.rank ?? 'unranked (no solved tasks)'}${behindOf(r.row).length ? '†' : ''} | ${r.row.harness} | ${vsCheapestCell(r)}${otherBasis(r) ? '‡' : ''} | ${costCell(r.row)} | ${pct(r.row.pass_rate)} ${range(r.row.pass_ci95, pct)} | ${r.row.wall_median_s.toFixed(1)} s |`);
  const behind = ranked.filter((r) => behindOf(r.row).length);
  const basis = ranked.filter(otherBasis);
  const correction = t.entry.paired_cost?.correction;
  if (behind.length || basis.length) out.push('');
  out.push(...behind.map((r) => `†${r.row.harness} is behind ${behindOf(r.row).join(' and ')} on pass rate in the run's preregistered test. Its rank is on cost only.`));
  if (basis.length) out.push(`‡Ranks and ratios use each trial record's own cost${correction ? ` after the [${correction.label}](${correction.link})${correction.cut ? ` and the [${correction.cut.label}](${correction.cut.link})` : ''}` : ''}, which comes to ${basis.map((r) => `${usd(r.cost!)} per solved task for ${r.row.harness} (shown: ${usd(r.row.usd_per_solved!)})`).join(', ')}.`);
  out.push('', RANKING_END);
  return out.join('\n');
}

/** The README with every ranking table regenerated. Refuses a marker with no end, an unknown or repeated run and model, a
 *  main entry's model with no table, and a Rank table outside the markers, so a hand-edited rank cannot pass --check. */
export function renderReadme(current: string, tables: Table[]): string {
  const mains = tables.filter((t) => t.entry.role === 'main');
  const lines = current.split('\n');
  const out: string[] = [];
  const seen = new Set<string>();
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    if (!line.includes('<!-- ranking:')) {
      if (/^\|\s*Rank\s*\|/.test(line)) throw new Error(`README.md line ${i + 1}: a Rank table outside the generated ranking markers; rank is computed by scripts/scoreboard/build.ts`);
      out.push(line);
      continue;
    }
    const m = RANKING_START.exec(line);
    if (!m || line !== m[0]) throw new Error(`README.md line ${i + 1}: not a ranking start marker on a line of its own: ${line.slice(0, 120)}`);
    const [, runId, model] = m;
    const key = `${runId}:${model}`;
    if (seen.has(key)) throw new Error(`README.md line ${i + 1}: a second ranking table for ${key}`);
    seen.add(key);
    const t = mains.find((x) => x.entry.run_id === runId);
    if (!t) throw new Error(`README.md line ${i + 1}: ${runId} is not a main scoreboard entry, so it has no ranking table`);
    const end = lines.findIndex((l, j) => j > i && l.includes('<!-- ranking:'));
    if (end < 0 || lines[end] !== RANKING_END) throw new Error(`README.md line ${i + 1}: the ranking table for ${key} has no ${RANKING_END} before the next marker`);
    out.push(renderRankingBlock(t, model!));
    i = end;
  }
  const missing = mains.flatMap((t) => [...new Set(t.entry.cells.map((c) => c.model))].map((model) => `${t.entry.run_id}:${model}`)).filter((k) => !seen.has(k));
  if (missing.length) throw new Error(`README.md has no ranking table for ${missing.join(', ')}; add ${rankingStart('<run id>', '<model>')} ... ${RANKING_END}`);
  return out.join('\n');
}

export const UNINDEXED_HEADING = '## Not yet indexed';
const GRADES: [ReportRow['grade'], string, string][] = [
  ['frontier', 'Frontier', 'Runs whose results rest on frontier models (Opus 5.5, GPT-6.1 Sol).'],
  ['method', 'Method', 'Pilots, calibration rounds and tooling checks: they test the method, not a harness or a part.'],
  ['appendix', 'Appendix', 'Sonnet, Haiku or luna runs: appendix-grade, not evidence about real use.'],
];

export function benchmarkFolders(root: string): string[] {
  const dir = join(root, 'docs/benchmarks');
  return readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && /^\d{4}-\d{2}-\d{2}-/.test(d.name)).map((d) => d.name).sort();
}

export function renderReportsIndex(rows: ReportRow[], folders: string[]): string {
  const cell = (s: string) => s.replaceAll('|', '\\|');
  const folderLink = (f: string) => `[${f}](benchmarks/${f}/)`;
  const out: string[] = [
    '# Reports index',
    '',
    '<!-- Generated by scripts/scoreboard/build.ts from docs/scoreboard/reports.json. Do not edit by hand. -->',
    '',
    'Every run folder under [benchmarks/](benchmarks/), one table per grade. Words are defined in the [glossary](glossary.md); new reports follow the [report standard](report-standard.md). This index holds no result numbers: read them in each report.',
    '',
  ];
  for (const [grade, title, blurb] of GRADES) {
    out.push(`## ${title}`, '', blurb, '', '| Folder | Question | Status | Claim check | Verdict | Superseded by | Note |', '|---|---|---|---|---|---|---|');
    for (const r of rows.filter((x) => x.grade === grade)) {
      out.push(`| [${r.folder}](benchmarks/${r.folder}/${r.report ?? 'PREREGISTRATION.md'}) | ${cell(r.question)} | ${r.status} | ${r.claim_check ?? 'none on record'} | ${r.verdict ? `**${r.verdict}**` : 'none'} | ${r.superseded_by ? folderLink(r.superseded_by) : ''} | ${cell(r.note ?? '')} |`);
    }
    out.push('');
  }
  const indexed = new Set(rows.map((r) => r.folder));
  const missing = folders.filter((f) => !indexed.has(f));
  out.push(UNINDEXED_HEADING, '', 'Run folders with no row in docs/scoreboard/reports.json yet. A new folder lands here until someone adds its row.', '');
  out.push(...(missing.length ? missing.map((f) => `- ${folderLink(f)}`) : ['None.']));
  return out.join('\n') + '\n';
}

export const withoutUnindexed = (page: string) => page.slice(0, page.indexOf(UNINDEXED_HEADING) < 0 ? undefined : page.indexOf(UNINDEXED_HEADING));

export function loadReports(root: string, folders: string[]): ReportRow[] {
  const rows = validateReports(JSON.parse(readFileSync(join(root, 'docs/scoreboard/reports.json'), 'utf8')), 'docs/scoreboard/reports.json');
  const errors: string[] = [];
  const seen = new Set<string>();
  for (const r of rows) {
    if (seen.has(r.folder)) errors.push(`reports.json: ${r.folder} has more than one row`);
    seen.add(r.folder);
    if (!folders.includes(r.folder)) { errors.push(`reports.json: no folder docs/benchmarks/${r.folder}`); continue; }
    const target = join(root, 'docs/benchmarks', r.folder, r.report ?? 'PREREGISTRATION.md');
    if (!existsSync(target)) errors.push(`reports.json: ${relative(root, target)} is missing`);
    if (r.superseded_by && !folders.includes(r.superseded_by)) errors.push(`reports.json: ${r.folder} is superseded by ${r.superseded_by}, which is not a folder`);
  }
  if (errors.length) throw new Error(errors.join('\n'));
  return rows;
}

export function loadEntries(root: string): Entry[] {
  const dir = join(root, 'docs/scoreboard/entries');
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => validateEntry(JSON.parse(readFileSync(join(dir, f), 'utf8')), `docs/scoreboard/entries/${f}`));
}

/** Reads a committed results file: JSON, or JSON lines (.jsonl) as a list. */
export const readResults = (root: string) => (p: string): unknown => {
  const text = readFileSync(join(root, p), 'utf8');
  return p.endsWith('.jsonl') ? text.split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l)) : JSON.parse(text);
};

export function buildAll(root: string): { page: string; readme: string; reportsIndex: string; tables: Table[] } {
  const cache = new Map<string, unknown>();
  const read = readResults(root);
  const readJson = (p: string) => { if (!cache.has(p)) cache.set(p, read(p)); return cache.get(p); };
  const entries = loadEntries(root);
  for (const e of entries) if (!existsSync(join(root, e.report))) throw new Error(`${e.run_id}: report ${e.report} is missing`);
  const tables = entries.map((e) => buildTable(e, readJson));
  const disclosures = (JSON.parse(readFileSync(join(root, 'docs/scoreboard/disclosures.json'), 'utf8')) as { lines: Record<string, string> }).lines;
  const page = renderPage(tables, disclosures);
  const readme = renderReadme(readFileSync(join(root, 'README.md'), 'utf8'), tables);
  const folders = benchmarkFolders(root);
  const reportsIndex = renderReportsIndex(loadReports(root, folders), folders);
  return { page, readme, reportsIndex, tables };
}

if (import.meta.main) {
  const root = join(import.meta.dir, '..', '..');
  const { page, readme, reportsIndex } = buildAll(root);
  const same = (a: string, b: string) => a === b;
  const targets: [string, string, (a: string, b: string) => boolean][] = [
    [join(root, 'docs/scoreboard.md'), page, same],
    [join(root, 'README.md'), readme, same],
    [join(root, 'docs/reports-index.md'), reportsIndex, (a, b) => withoutUnindexed(a) === withoutUnindexed(b)],
  ];
  if (process.argv.includes('--check')) {
    const stale = targets.filter(([p, want, eq]) => !existsSync(p) || !eq(readFileSync(p, 'utf8'), want)).map(([p]) => relative(root, p));
    if (stale.length) { console.error(`scoreboard: out of date: ${stale.join(', ')}; run bun scripts/scoreboard/build.ts (README ranks are recomputed from the results, so a results change can move a rank: say so in the changelog)`); process.exit(1); }
    console.log('scoreboard: up to date');
  } else {
    for (const [p, want] of targets) writeFileSync(p, want);
    console.log('scoreboard: wrote docs/scoreboard.md, docs/reports-index.md and the README ranking tables');
  }
}
