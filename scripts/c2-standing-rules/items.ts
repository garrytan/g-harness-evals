// The C2 standing-rules eval's items (docs/benchmarks/2026-12-c2-standing-rules/PREREGISTRATION.md): 70 counted items and 3 pilot
// items (101 to 103), fully synthetic. Each item plants one wrong fact or way of working on a brain page, scripts session 1 (a
// question that draws the mistake, then the correction in fixed words) and session 2's probe (a short writing task saved to
// out.md, where the mistake would show), with the strings the scorer looks for. The arms differ only in the last sentence of
// the correction (CORRECTION_SUFFIX). The 30 coding-check rules fill the standing-rules section to its 1,500-character cap.
// Nothing here calls a model or reads a key.

export type ItemKind = 'role' | 'value' | 'practice';
export type CorrectionArm = 'rules' | 'control' | 'remember' | 'floor';

export interface Item {
  id: number;
  kind: ItemKind;
  /** The brain page the wrong fact is on, and the entity the correction is about. */
  page: { slug: string; title: string; type: 'person' | 'company'; body: string };
  /** Planted by the owner with gbrain remember before session 1. */
  wrong_fact: string;
  /** Session 1, turn 1: a question whose honest answer from the brain shows the mistake. */
  question: string;
  /** Session 1, turn 2: the user's correction in fixed words, before the arm's suffix. */
  correction: string;
  /** Session 2: the probe, a writing task saved to out.md in the session's folder. */
  probe: string;
  /** Every group must match out.md (any one spelling in the group). */
  expect: string[][];
  /** No entry may match out.md outside a negation window (score.ts). */
  reject: string[];
}

/** The arms' only difference in session 1 (the floor arm sends no correction at all; the control arm's words are the rules arm's). */
