#!/usr/bin/env python3
"""Build the rules-at-scale Ubicloud lane from scripts/ubicloud/ without editing it.

scripts/ubicloud/{fanout,run-shard,vm-shard}.sh are frozen while the harness shootout runs, and none
of their workloads can start scripts/rules-at-scale/run-shard.sh: the harness workload always runs scripts/run-shard.sh
and builds its smoke from tasks/multiuser, and frontier-harbor always runs the pinned scripts/frontier-harbor/vm-run.sh
(and its controller asks an OpenAI cell for a zero-data-retention check that only frontier install checks produce). So
this script reads those three files as they are in this checkout, applies the patches below (each anchor must match
exactly as often as stated, or it stops with exit 2 and names the anchor) and writes the patched copies into a lane
directory, beside a symlink to every other file of scripts/ubicloud/. The wrappers fanout.sh and run-shard.sh beside this
file run the patched copies with --workload rules-at-scale. Everything the patches do not touch (the VM, the keys, the
pulls, the mirror, the teardown, the quota, the TTL) is scripts/ubicloud/ as it stands.

    python3 scripts/rules-at-scale/ubicloud/lane.py <repository root>   # prints the lane directory

The lane directory is <RAS_LANE_ROOT or $XDG_CACHE_HOME/rules-at-scale-ubicloud or ~/.cache/rules-at-scale-ubicloud>/<key>,
the key a sha256 over the repository root and the patched files, so an unchanged checkout reuses it.
"""
import hashlib, os, shlex, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PATCHED = ('fanout.sh', 'run-shard.sh', 'vm-shard.sh')


def note(name):
    return ('#!/usr/bin/env bash\n# GENERATED by scripts/rules-at-scale/ubicloud/lane.py from scripts/ubicloud/' + name +
            ' with --workload rules-at-scale added (scripts/rules-at-scale/ubicloud/README.md). Do not edit; run the wrapper.\n')


def patches(root):
    vm_block = open(os.path.join(HERE, 'vm-rules-at-scale.sh')).read()
    w_old = 'harness, gstack-laneb, qm-driver or frontier-harbor'
    return {
        'fanout.sh': [
            ('#!/usr/bin/env bash\n', note('fanout.sh'), 1),
            ('case $workload in harness|gstack-laneb|qm-driver|frontier-harbor) ;; *) echo "fanout: --workload must be ' + w_old + '"',
             'case $workload in harness|gstack-laneb|qm-driver|frontier-harbor|rules-at-scale) ;; *) echo "fanout: --workload must be harness, gstack-laneb, qm-driver, frontier-harbor or rules-at-scale"', 1),
            # rules-at-scale writes collect.ts's rules-trials.jsonl, which merge-shards.ts does not read: print the results directories
            ('case $workload in qm-driver|frontier-harbor) echo', 'case $workload in qm-driver|frontier-harbor|rules-at-scale) echo', 2),
        ],
        'run-shard.sh': [
            ('#!/usr/bin/env bash\n', note('run-shard.sh'), 1),
            # the lane directory is not under the repository, so the repository root is fixed here
            ('root=$(cd "$here/../.." && pwd)\n', 'root=' + shlex.quote(root) + '\n', 1),
            ('  *) echo "run-shard (ubicloud): --workload must be ' + w_old + '" >&2; exit 2 ;;\n',
             '  rules-at-scale)\n  [ "$embedded" -eq 0 ] && [ -z "$sealed_root" ] && [ -z "$opening_receipt" ] || { echo "run-shard (ubicloud): --workload rules-at-scale takes no --embedded, --sealed-root or --opening-receipt" >&2; exit 2; } ;;\n'
             '  *) echo "run-shard (ubicloud): --workload must be harness, gstack-laneb, qm-driver, frontier-harbor or rules-at-scale" >&2; exit 2 ;;\n', 1),
            # the mirror leaves out the request captures and both Harbor job trees (results/run and smoke/results/run)
            ('  [ "$workload" != frontier-harbor ] || mapfile -t found < <(finished_trees)\n',
             '  [ "$workload" != frontier-harbor ] || mapfile -t found < <(finished_trees)\n'
             '  [ "$workload" != rules-at-scale ] || skip=(--exclude=proxy-capture --exclude=./results/run --exclude=./smoke/results/run)\n', 1),
            # a mid-run pull skips the container-owned files of a live Harbor trial instead of failing
            ('  [ "$workload" != frontier-harbor ] || skip=(--skip-unreadable)\n',
             '  [ "$workload" != frontier-harbor ] && [ "$workload" != rules-at-scale ] || skip=(--skip-unreadable)\n', 1),
            # stopping the shard waits up to 240 s for the exit file, so run-shard.sh drains its meter and writes its rows
            ('    if [ "$workload" = gstack-laneb ] || [ "$workload" = frontier-harbor ]; then\n',
             '    if [ "$workload" = gstack-laneb ] || [ "$workload" = frontier-harbor ] || [ "$workload" = rules-at-scale ]; then\n', 1),
            ('  case $(jq1 workload) in gstack-laneb|qm-driver|frontier-harbor) workload=$(jq1 workload) ;; esac\n',
             '  case $(jq1 workload) in gstack-laneb|qm-driver|frontier-harbor|rules-at-scale) workload=$(jq1 workload) ;; esac\n', 1),
        ],
        'vm-shard.sh': [
            ('#!/usr/bin/env bash\n', note('vm-shard.sh'), 1),
            ('phase checkout_end\n\n', 'phase checkout_end\n\n' + vm_block.rstrip('\n') + '\n\n', 1),
        ],
    }


def build(root):
    src = os.path.join(root, 'scripts', 'ubicloud')
    out = {}
    for name, edits in patches(root).items():
        text = open(os.path.join(src, name)).read()
        for old, new, count in edits:
            n = text.count(old)
            if n != count:
                print('lane.py: scripts/ubicloud/%s has %d of the anchor %r, not %d; scripts/ubicloud changed, so update the patches in scripts/rules-at-scale/ubicloud/lane.py' % (name, n, old[:120], count), file=sys.stderr)
                sys.exit(2)
            text = text.replace(old, new)
        out[name] = text
    links = sorted(f for f in os.listdir(src) if f not in PATCHED and not f.startswith('.'))
    key = hashlib.sha256()
    for part in [root, *links, *(out[n] for n in PATCHED)]:
        key.update(part.encode() + b'\0')
    base = os.environ.get('RAS_LANE_ROOT') or os.path.join(os.environ.get('XDG_CACHE_HOME') or os.path.join(os.path.expanduser('~'), '.cache'), 'rules-at-scale-ubicloud')
    lane = os.path.join(base, key.hexdigest()[:16])
    if os.path.isfile(os.path.join(lane, '.complete')):
        return lane
    os.makedirs(base, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix='.build-', dir=base)
    for f in links:
        os.symlink(os.path.join(src, f), os.path.join(tmp, f))
    for name in PATCHED:
        p = os.path.join(tmp, name)
        open(p, 'w').write(out[name])
        os.chmod(p, 0o755)
    open(os.path.join(tmp, '.complete'), 'w').write(root + '\n')
    try:
        os.rename(tmp, lane)
    except OSError:
        if not os.path.isfile(os.path.join(lane, '.complete')):
            raise
    return lane


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print('usage: lane.py <repository root>', file=sys.stderr)
        sys.exit(2)
    print(build(os.path.abspath(sys.argv[1])))
