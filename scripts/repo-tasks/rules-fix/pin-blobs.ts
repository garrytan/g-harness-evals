// Pins every file of each task's verifier/tests.tar to its upstream git blob, so the test files can ship as a tar that
// review does not read and still be checked byte for byte against the upstream commits in sources.json. For each task it
// lists the base commit's tree (protected/ files) and the fix commit's tree (hidden/ files) in a blobless clone of the
// upstream repository and writes upstream-blobs.json: per task, the two commits and each file's git mode and blob id.
// Anyone can recheck an entry with `git ls-tree <commit> -- <path>` in a clone of the repository. It refuses a file the
// upstream commit does not hold. Needs network access to GitHub; tests/rules-fix-build.test.ts reads only the JSON.
//
//   bun scripts/repo-tasks/rules-fix/pin-blobs.ts [--clones <dir>]
import { existsSync, mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { baseTree, fixFiles, keyOf, plan, SOURCES, verifierTests } from './build.ts';
import { git } from '../delivery/lib.ts';

export const BLOBS = join(import.meta.dir, 'upstream-blobs.json');

function lsTree(dir: string, commit: string, paths: string[]): Map<string, [string, string]> {
  const out = new Map<string, [string, string]>();
  for (let i = 0; i < paths.length; i += 200) {
    for (const line of git(dir, ['ls-tree', '-r', '--full-tree', commit, '--', ...paths.slice(i, i + 200)]).split('\n').filter(Boolean)) {
      const m = /^(\d+) blob ([0-9a-f]{40})\t(.+)$/.exec(line);
      if (m) out.set(m[3]!, [m[1]!, m[2]!]);
    }
  }
  return out;
}

if (import.meta.main) {
  const i = process.argv.indexOf('--clones');
  const clones = i > 0 ? resolve(process.argv[i + 1]!) : mkdtempSync(join(tmpdir(), 'rf-pin-'));
  mkdirSync(clones, { recursive: true });
  const tasks: Record<string, { repo: string; base: string; fix: string; protected: Record<string, [string, string]>; hidden: Record<string, [string, string]> }> = {};
  const missing: string[] = [];
  for (const row of plan()) {
    const t = row.task;
    const dir = join(clones, t.repo);
    if (!existsSync(join(dir, '.git'))) git(clones, ['clone', '-q', '--filter=blob:none', '--no-checkout', SOURCES.repos[t.repo].url, t.repo]);
    const files = verifierTests(t, baseTree(t), fixFiles(t).tests);
    const entry = { repo: t.repo, base: t.base, fix: t.fix, protected: {}, hidden: {} } as (typeof tasks)[string];
    for (const [side, commit] of [['protected', t.base], ['hidden', t.fix]] as const) {
      const paths = [...files.keys()].filter((p) => p.startsWith(side + '/')).map((p) => p.slice(side.length + 1)).sort();
      const listed = lsTree(dir, commit, paths);
      for (const p of paths) { const b = listed.get(p); if (b) entry[side][p] = b; else missing.push(row.id + ' ' + keyOf(t) + ' ' + side + '/' + p); }
    }
    tasks[row.id] = entry;
  }
  if (missing.length) { console.error('PIN: refused, not in the upstream commit:\n' + missing.join('\n')); process.exit(1); }
  writeFileSync(BLOBS, JSON.stringify({ note: "Generated by scripts/repo-tasks/rules-fix/pin-blobs.ts: each file of a task's verifier/tests.tar as [git mode, git blob id] at the upstream commit (protected/ at base, hidden/ at fix).", tasks }, null, 1) + '\n');
  console.log('PIN: tasks=' + Object.keys(tasks).length + ' files=' + Object.values(tasks).reduce((n, e) => n + Object.keys(e.protected).length + Object.keys(e.hidden).length, 0));
}
