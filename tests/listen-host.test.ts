// The per-trial servers (metering proxy, world) never listen on every interface: the loopback, or the docker bridge
// gateway when containers must reach them (2026-10-28, after shard VMs with a public address ran the proxy on 0.0.0.0).
import { describe, expect, test } from 'bun:test';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const run = (env: Record<string, string>, code: string) => Bun.spawnSync([process.execPath, '-e', code], { cwd: ROOT, env: { PATH: process.env.PATH, HOME: process.env.HOME, ...env }, stdout: 'pipe', stderr: 'pipe' });

describe('listen host', () => {
  // Generated by the ship Step 7 coverage audit.
  // Value: protects=gateway discovery and fail-closed Docker errors;
  // fails_when=the runner hardcodes an address or falls back to a wildcard;
  // why_new=existing host tests only supply an explicit override; seam=none;
  // no_claim=container reachability or external isolation, only Docker inspection and discovery.
  test('reads the gateway from docker network inspect and refuses an unavailable docker command', () => {
    const code = "import { listenHost } from './runner/trial/world.ts'; console.log(listenHost(true));";
    const fakeBin = mkdtempSync(join(tmpdir(), 'fake-docker-'));
    try {
      writeFileSync(join(fakeBin, 'docker'), '#!/bin/sh\n[ "$1 $2 $3" = "network inspect bridge" ] || exit 1\nprintf "10.9.8.7\\n"\n', { mode: 0o755 });
      const found = run({ PATH: fakeBin }, code);
      expect(found.stderr.toString()).toBe('');
      expect(found.stdout.toString().trim()).toBe('10.9.8.7');
    } finally { rmSync(fakeBin, { recursive: true, force: true }); }
    const missing = run({ PATH: '/nonexistent' }, code);
    expect(missing.exitCode).not.toBe(0);
    expect(missing.stderr.toString()).toContain('HE-PROXY-004');
    expect(missing.stderr.toString()).toContain('docker network inspect bridge');
  });

  const docker = Bun.spawnSync(['docker', 'network', 'inspect', 'bridge', '--format', '{{(index .IPAM.Config 0).Gateway}}'], { stdout: 'pipe', stderr: 'pipe' });
  test.skipIf(docker.exitCode !== 0)('with a docker daemon, the gateway is the default bridge network\'s', () => {
    const found = run({}, "import { listenHost } from './runner/trial/world.ts'; console.log(listenHost(true));");
    expect(found.exitCode).toBe(0);
    expect(found.stdout.toString().trim()).toBe(docker.stdout.toString().trim());
  });

  // Generated by the ship Step 7 coverage audit.
  // Value: protects=world local HTTP and container URL use the selected bind address;
  // fails_when=world binding or local requests still assume every interface or 127.0.0.1;
  // why_new=existing tests inspect host strings but never start a world on another address; seam=none;
  // no_claim=real bridge routing, a second loopback address stands in for the host-owned gateway.
  test('the world serves local admin calls on the selected host while advertising the container route', () => {
    const result = run({ HE_CONTAINER_HOST_IP: '127.0.0.2' }, `
      import { mkdtempSync, rmSync } from 'node:fs';
      import { tmpdir } from 'node:os';
      import { join } from 'node:path';
      import { TrialWorld } from './runner/trial/world.ts';
      const dir = mkdtempSync(join(tmpdir(), 'world-bind-'));
      let world;
      try {
        world = new TrialWorld({ trialId: 'bind-test', split: 'dev', actors: ['dana-okafor'], outDir: dir, reachableFromContainers: true });
        const now = await world.advanceClock(1);
        console.log(JSON.stringify({ local: world.localUrl, harness: world.harnessUrl, now }));
      } finally { world?.stop(); rmSync(dir, { recursive: true, force: true }); }
    `);
    expect(result.stderr.toString()).toBe('');
    expect(result.exitCode).toBe(0);
    const output = JSON.parse(result.stdout.toString());
    expect(new URL(output.local).hostname).toBe('127.0.0.2');
    expect(new URL(output.harness).hostname).toBe('host.docker.internal');
    expect(new URL(output.harness).port).toBe(new URL(output.local).port);
    expect(Number.isFinite(Date.parse(output.now))).toBe(true);
  });

  // Generated by the ship Step 7 coverage audit.
  // Value: protects=run proxy readiness and authenticated controls use its selected bind address;
  // fails_when=readiness, control calls, or process URLs still use fixed loopback;
  // why_new=MeteringProxy tests bypass the RunProxy subprocess wrapper; seam=none;
  // no_claim=provider forwarding or Docker routing, this uses a second loopback address and no provider keys.
  test('the run proxy starts, binds, finalizes and unbinds on the selected host', () => {
    const result = run({ HE_CONTAINER_HOST_IP: '127.0.0.2' }, `
      import { mkdtempSync, rmSync } from 'node:fs';
      import { tmpdir } from 'node:os';
      import { join } from 'node:path';
      import { RunProxy } from './runner/trial/proxy.ts';
      const dir = mkdtempSync(join(tmpdir(), 'run-proxy-bind-'));
      let proxy;
      try {
        proxy = await RunProxy.start({ runId: 'bind-test', runDir: dir, ledgerPath: join(dir, 'ledger.sqlite'), leaseUsd: 1, allowModels: [], reachableFromContainers: true, startTimeoutMs: 3000 });
        await proxy.bind('trial', 'trial-key', 'placeholder-trial-token');
        const local = proxy.baseUrlFor('trial', 'openai', false);
        const refused = await fetch(local + '/v1/models');
        const meter = await proxy.finalize('trial-key');
        await proxy.unbind('trial');
        const unbound = await fetch(local + '/v1/models');
        console.log(JSON.stringify({ local, container: proxy.baseUrlFor('trial', 'openai'), meter, refused: refused.status, unbound: await unbound.json() }));
      } finally { await proxy?.stop(); rmSync(dir, { recursive: true, force: true }); }
    `);
    expect(result.stderr.toString()).toBe('');
    expect(result.exitCode).toBe(0);
    const output = JSON.parse(result.stdout.toString());
    expect(new URL(output.local).hostname).toBe('127.0.0.2');
    expect(new URL(output.container).hostname).toBe('host.docker.internal');
    expect(new URL(output.container).port).toBe(new URL(output.local).port);
    expect(output.refused).toBe(403);
    expect(output.meter.requests).toBe(0);
    expect(output.unbound.error.message).toContain('slot trial is not bound');
  }, 15_000);

  test('loopback when containers need no route; the bridge gateway (HE_CONTAINER_HOST_IP or docker network inspect) when they do; never a wildcard', () => {
    const code = "import { listenHost } from './runner/trial/world.ts'; console.log(listenHost(false), listenHost(true));";
    const ok = run({ HE_CONTAINER_HOST_IP: '10.9.8.7' }, code);
    expect(ok.stdout.toString().trim()).toBe('127.0.0.1 10.9.8.7');
    const spelled = run({ HE_CONTAINER_HOST_IP: '00.0.0.0' }, code);
    expect(spelled.exitCode).not.toBe(0);
    expect(spelled.stderr.toString()).toContain('HE-PROXY-004');
    const wildcard = run({ HE_CONTAINER_HOST_IP: '0.0.0.0' }, code);
    expect(wildcard.exitCode).not.toBe(0);
    expect(wildcard.stderr.toString()).toContain('HE-PROXY-004');
    const junk = run({ HE_CONTAINER_HOST_IP: 'host.docker.internal' }, code);
    expect(junk.exitCode).not.toBe(0);
    expect(junk.stderr.toString()).toContain('HE-PROXY-004');
  });

  test('no runner, world, harness or script source binds 0.0.0.0', () => {
    const files: string[] = [];
    const walk = (dir: string) => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (f === 'node_modules' || f === '.build') continue; if (statSync(p).isDirectory()) walk(p); else if (/\.(ts|sh)$/.test(f)) files.push(p); } };
    for (const d of ['runner', 'world', 'harnesses', 'scripts']) walk(join(ROOT, d));
    const offenders = files.filter((f) => /(hostname:\s*['"]0\.0\.0\.0['"]|--listen['",\s]+['"]?0\.0\.0\.0:|--bind\s+0\.0\.0\.0)/.test(readFileSync(f, 'utf8').split('\n').filter((l) => !/^\s*(\/\/|#|\*)/.test(l)).join('\n')));
    expect(offenders.map((f) => f.slice(ROOT.length + 1))).toEqual([]);
  });
});
